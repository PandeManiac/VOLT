namespace Volt.Ui.Text;

/// <summary>
/// Identifies one of the font faces embedded in Volt.Ui.
/// </summary>
public enum UiFontKind
{
	/// <summary>
	/// The proportional interface face (IBM Plex Sans, SIL OFL 1.1).
	/// </summary>
	Sans = 0,

	/// <summary>
	/// The monospaced face used for code, logs, and numeric fields
	/// (JetBrains Mono, SIL OFL 1.1).
	/// </summary>
	Monospace = 1
}
